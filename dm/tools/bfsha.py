#!/usr/bin/env python3
"""The game's shader archives (FSHA, .bfsha): which program of a shading model each BNSH variation is, named by its options, a name that holds across versions of
the game where the variation's index and its shaders' keys do not (dm/tools/pso_carry.py; docs/reference/packing.md#a-derived-profiles-prewarm-list-names-another-versions-shaders).

Layout (FSHA 0x00090101, Ocarina of Time 1.0.0 and 1.1.1): +0x20 the archive; archive +0x10 its shading models (0x100 bytes each), +0x40 their count. A model: +0x00
name, +0x08 / +0x18 its static and dynamic options (0x28 bytes each), +0x88 its programs (0x40 bytes each, +0x20 the program's BNSH variation), +0x90 the key table
(static + dynamic key words per program), +0xa8 its BNSH, +0xe4 the counts (static options, dynamic options, programs: u16; key words: u8, u8). An option: +0x00 name,
+0x08 its choices (a dictionary, in choice order), +0x20 the mask of its key word, +0x24 the word's index and the shift. Strings are a u16 length and the bytes.

python3 dm/tools/bfsha.py <RomFS> <shader_map.tsv> <out shader_programs.tsv>: the program of each shader map key whose source is a shader archive's BNSH variation.
"""
USAGE = 'python3 dm/tools/bfsha.py <RomFS> <shader_map.tsv> <out shader_programs.tsv>'
import collections
import hashlib
import os
import re
import struct
import sys

VERSION = 0x00090101
SOURCE = re.compile(r'^(.*\.bfsha(?:\.zs)?)#BNSH@(0x[0-9a-f]+)#var(\d+)$')
STAGE = {'vertex': 'vs', 'pixel': 'ps', 'task': 'ts', 'mesh': 'ms', 'compute': 'cs'}
HEAD = ('# kind: evidence  the program of each shader map key from a shader archive (BFSHA), where its source column names the variation: the shading model and a digest '
        'of its options (sha256 of the sorted name=choice lines, 16 hex digits), the same in every version of the game whose program has those options '
        '(generated by dm/tools/bfsha.py, do not edit; read by dm/tools/pso_carry.py)\n')


class Unread(ValueError):
    pass


def _string(d, at):
    n = struct.unpack_from('<H', d, at)[0]
    return d[at + 2:at + 2 + n].decode('utf-8', 'replace')


def _names(d, at):   # a dictionary: u32 signature, u32 count, then count + 1 nodes of 16 bytes (the root first), the name at +8
    n = struct.unpack_from('<I', d, at + 4)[0]
    return [_string(d, struct.unpack_from('<Q', d, at + 8 + 16 * i + 8)[0]) for i in range(1, n + 1)]


def _options(d, at, n):
    out = []
    for i in range(n):
        o = at + 0x28 * i
        name, choices = struct.unpack_from('<QQ', d, o)
        mask, word, shift = struct.unpack_from('<IBB', d, o + 0x20)
        out.append((_string(d, name), _names(d, choices), word, mask, shift))
    return out


def programs(d, where='shader archive'):
    """→ [(model name, BNSH offset, {variation: options digest})]"""
    if d[:8] != b'FSHA    ': raise Unread(f'{where}: not a shader archive (FSHA)')
    if struct.unpack_from('<I', d, 8)[0] != VERSION: raise Unread(f'{where}: FSHA version {struct.unpack_from("<I", d, 8)[0]:#010x}, only {VERSION:#010x} is read')
    try:
        arc = struct.unpack_from('<Q', d, 0x20)[0]
        models, count = struct.unpack_from('<Q', d, arc + 0x10)[0], struct.unpack_from('<H', d, arc + 0x40)[0]
        out = []
        for m in range(count):
            b = models + 0x100 * m
            name = _string(d, struct.unpack_from('<Q', d, b)[0])
            sopt, dopt = struct.unpack_from('<Q', d, b + 0x08)[0], struct.unpack_from('<Q', d, b + 0x18)[0]
            progs, keys = struct.unpack_from('<QQ', d, b + 0x88)
            bnsh = struct.unpack_from('<Q', d, b + 0xa8)[0]
            ns, nd, npg, sk, dk = struct.unpack_from('<HHHBB', d, b + 0xe4)
            if d[bnsh:bnsh + 4] != b'BNSH': raise Unread(f'{where}: shading model {name}: no BNSH at {bnsh:#x}')
            nvar, pvar = struct.unpack_from('<IQ', d, bnsh + 0x7c)
            opts, words = _options(d, sopt, ns) + _options(d, dopt, nd), sk + dk
            ids = {}
            for i in range(npg):
                vp = struct.unpack_from('<Q', d, progs + 0x40 * i + 0x20)[0]
                v, r = divmod(vp - bnsh - pvar, 0x40)
                if r or not 0 <= v < nvar or v in ids: raise Unread(f'{where}: shading model {name}: program {i} points at no variation of its own ({vp:#x})')
                key = struct.unpack_from(f'<{words}I', d, keys + 4 * words * i)
                vals = []
                for oname, choices, word, mask, shift in opts:
                    c = (key[word] & mask) >> shift
                    vals.append(f'{oname}={choices[c] if c < len(choices) else f"#{c}"}')
                ids[v] = hashlib.sha256('\n'.join(sorted(vals)).encode()).hexdigest()[:16]
            out.append((name, bnsh, ids))
        return out
    except (struct.error, IndexError) as e: raise Unread(f'{where}: {e}') from e


def _split():
    """dm/gfx/tools/shader_split.py, the reader of the game's containers; imported on first use, as it loads the game profile"""
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '../gfx/tools'))
    import shader_split
    return shader_split


_DICTS = {}


def read_member(romfs, path):
    """A file of the RomFS by the shader map's path, zstd (with the RomFS's dictionaries) or Yaz0 opened; past a SARC, the rest of the path names its member"""
    try: return _read_member(romfs, path)
    except SystemExit as e: raise Unread(str(e).removeprefix('[RED] ')) from e   # shader_split's red()


def _read_member(romfs, path):
    ss = _split()
    if romfs not in _DICTS: _DICTS[romfs] = ss.zs_dicts(romfs)
    if ss.ZDICTS is not _DICTS[romfs]: ss._pool_init(_DICTS[romfs]); ss._ZD.clear()
    def opened(d, name):
        if name.endswith('.zs'): d = ss.unzs_dict(d, ss.zs_dict_id(d), path) if ss.zs_dict_id(d) else ss.zstd_mod().decompress(d)
        return ss.yaz0(d, path) if d[:4] == b'Yaz0' else d
    parts = path.strip('/').split('/')
    for i in range(1, len(parts) + 1):
        at = os.path.join(romfs, *parts[:i])
        if ss.os.path.isfile(at): d, rest = opened(ss.open(at, 'rb').read(), at), '/'.join(parts[i:]); break
    else: raise Unread(f'{path}: not in {romfs}')
    while rest:
        if d[:4] != b'SARC': raise Unread(f'{path}: {rest} is inside a file that is not a SARC')
        hit = next(((n, m) for n, m in ss.sarc_members(d, path) if rest == n or rest.startswith(n + '/')), None)
        if hit is None: raise Unread(f'{path}: no member {rest}')
        d, rest = opened(hit[1], hit[0]), rest[len(hit[0]) + 1:]
    return d


def variation_keys(d, bnsh, where):
    """{variation: {stage: key}} of the BNSH at bnsh, as the shader split keys them"""
    ss = _split()
    out = collections.defaultdict(dict)
    try: found = ss.bnsh_shaders(d, bnsh, where)
    except SystemExit as e: raise Unread(str(e).removeprefix('[RED] ')) from e
    for label, st, ctl, code in found: out[int(label.rsplit('#var', 1)[1])][st] = ss.skey(ctl, code)
    return out


def sources(shader_map):
    """→ {file: [(key, stage, BNSH offset, variation)]} for the map's keys whose source is a shader archive's variation"""
    out = collections.defaultdict(list)
    with open(shader_map, encoding='utf-8') as f:
        for ln in f:
            c = ln.rstrip('\n').split('\t')
            if len(c) < 5 or ln.startswith(('#', 'package\t')): continue
            m = SOURCE.match(c[4])
            if m: out[m[1]].append((c[3], c[2], int(m[2], 16), int(m[3])))
    return out


def write_table(romfs, shader_map, out_path):
    rows, missing = [], 0
    for path, keys in sorted(sources(shader_map).items()):
        at = {bnsh: (name, ids) for name, bnsh, ids in programs(read_member(romfs, path), path)}
        for key, _, bnsh, var in keys:
            name, ids = at.get(bnsh, (None, {}))
            if var in ids: rows.append(f'{key}\t{name}\t{ids[var]}\n')
            else: missing += 1
    with open(out_path + '.partial', 'w', encoding='utf-8') as f:
        f.writelines([HEAD, 'key\tmodel\toptions\n'] + sorted(rows))
    os.replace(out_path + '.partial', out_path)
    return len(rows), missing


def read_table(path):
    """key → (model, options digest); {} without the table"""
    out = {}
    try:
        with open(path, encoding='utf-8') as f:
            for ln in f:
                c = ln.rstrip('\n').split('\t')
                if len(c) == 3 and not ln.startswith(('#', 'key\t')): out[c[0]] = (c[1], c[2])
    except FileNotFoundError: pass
    return out


if __name__ == '__main__':
    if len(sys.argv) != 4: sys.exit(USAGE)
    n, missing = write_table(*sys.argv[1:])
    print(f'{n:,} keys' + (f'; {missing:,} whose variation no program names' if missing else ''))
    if missing: sys.exit(f'[RED] {missing} shader map key(s) from a shader archive whose variation no program of its model names')
