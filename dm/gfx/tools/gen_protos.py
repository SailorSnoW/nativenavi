#!/usr/bin/env python3
# Generates nvn_protos.h from nvn.h's PFNNVN*PROC prototypes. Apple arm64 extends narrow integer arguments in the caller, AAPCS64 does not: NVNboolean
# becomes uint32_t; other narrow parameters and stack-passed arguments are failures.
# Usage: gen_protos.py <nvn.h> <name table, one a line in load order> <output .h>
import re, sys

hdr, names_path, out = sys.argv[1:4]
src = open(hdr).read()
protos = {}
for m in re.finditer(r'typedef\s+([\w\s\*]+?)\s*\(\*PFNNVN(\w+)PROC\)\s*\(([^;]*?)\);', src, re.S):
    ret, key, args = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
    protos[key] = (ret, [a.strip() for a in args.split(',')] if args.strip() not in ('', 'void') else [])

FP = re.compile(r'^(const\s+)?(float|double)$')
SMALL = re.compile(r'^(const\s+)?(uint8_t|int8_t|uint16_t|int16_t|char|unsigned char|short|unsigned short|bool)$')
names = [l.strip() for l in open(names_path) if l.strip()]


def param_type(a):
    w = a.split()
    if a.endswith('*') or len(w) < 2 or w[-1] in ('int', 'float', 'double', 'char') or w[-1].endswith('_t') or w[-1].startswith(('NVN', 'PFN')): return a
    return re.sub(r'\s+\w+$', '', a)


lines = ['// Generated by dm/gfx/tools/gen_protos.py; do not edit. NVNboolean parameters are replaced with uint32_t.', '#pragma once', '#include "nvn.h"', '']
red, missing = [], []
for n in names:
    key = n[3:].upper()
    if key not in protos:
        missing.append(n)
        continue
    ret, args = protos[key]
    gp = fp = 0
    conv = []
    for a in args:
        t = param_type(a).strip()
        if FP.match(t): fp += 1
        else: gp += 1
        if t == 'NVNboolean': t = 'uint32_t'
        elif SMALL.match(t): red.append(f'{n}: <32-bit argument {t}')
        conv.append(t)
    if gp > 8 or fp > 8: red.append(f'{n}: arguments on the stack gp={gp} fp={fp}')
    lines.append(f'typedef {ret} (*NVNT_{n})({", ".join(conv) if conv else "void"});')
lines.append('')
lines.append('// Names without a prototype in the header (newer interfaces): they can only get named stubs')
for n in missing: lines.append(f'//   {n}')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'prototypes {len(names) - len(missing)} / names {len(names)}; without a prototype {len(missing)}; [RED] {len(red)}')
for r in red: print('  [RED]', r)

# _nvnth_<i>: count nvn_slot[i].cnt, jump to its fn; x16 (scratch) still points to the slot on entry, for nvn_unimpl_entry
th = out.replace('nvn_protos.h', 'nvn_thunks.S')
S = ['// Generated by dm/gfx/tools/gen_protos.py; do not edit.',
     "// Counting uses the LSE atomic stadd (ARMv8.1; every Apple chip since A12 / M1 has it): the next line keeps this file independent of the compiler's -mcpu baseline.",
     '    .arch_extension lse', '    .text', '    .p2align 2']
for i, n in enumerate(names):
    S += [f'    .globl _nvnth_{i}', f'_nvnth_{i}:',
          '    adrp x16, _nvn_slot@PAGE', '    add x16, x16, _nvn_slot@PAGEOFF',
          f'    mov x17, #{i * 16}', '    add x16, x16, x17',
          '    mov x17, #1', '    stadd x17, [x16]', '    ldr x17, [x16, #8]', '    br x17']
# _nvnthf_<i>: uncounted: the count's shared atomic add costs hot functions more than their own time
for i, n in enumerate(names):
    S += [f'    .globl _nvnthf_{i}', f'_nvnthf_{i}:',
          '    adrp x16, _nvn_slot@PAGE', '    add x16, x16, _nvn_slot@PAGEOFF',
          f'    mov x17, #{i * 16}', '    add x16, x16, x17',
          '    ldr x17, [x16, #8]', '    br x17']
S += ['    .data', '    .p2align 3', '    .globl _nvn_thunk', '_nvn_thunk:'] + [f'    .quad _nvnth_{i}' for i in range(len(names))]
S += ['    .globl _nvn_thunk_fast', '_nvn_thunk_fast:'] + [f'    .quad _nvnthf_{i}' for i in range(len(names))]
S += ['    .globl _nvn_names', '_nvn_names:'] + [f'    .quad Ln{i}' for i in range(len(names))]
S += ['    .cstring'] + [f'Ln{i}: .asciz "{n}"' for i, n in enumerate(names)]
open(th, 'w').write('\n'.join(S) + '\n')
hn = out.replace('nvn_protos.h', 'nvn_count.h')
open(hn, 'w').write('// Generated by gen_protos.py\n#pragma once\n#define NVN_NFUNC %d\n' % len(names))
